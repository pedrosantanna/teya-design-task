// Writes src/design-system/components/Map/style.generated.ts: the Map's light and dark MapLibre styles, built
// from the theme's colours by map-style.mjs. Run after `npm run tokens` (npm run map).
//   node scripts/build-map-style.mjs          write the file
//   node scripts/build-map-style.mjs --check  fail if the file is out of date (part of npm run check)
import { readFileSync, writeFileSync } from 'node:fs';

import { buildMapStyle, MAP_CAMERA, themeColours } from './map-style.mjs';

const out = new URL('../src/design-system/components/Map/style.generated.ts', import.meta.url).pathname;
const { light, dark } = await themeColours();
const styles = { light: buildMapStyle(light, 'light'), dark: buildMapStyle(dark, 'dark') };
const output = `// Generated by scripts/build-map-style.mjs from the theme. Do not edit; run \`npm run map\`.
/* eslint-disable */
import type { StyleSpecification } from '@maplibre/maplibre-react-native';

export const MAP_CAMERA = ${JSON.stringify(MAP_CAMERA)} as const;

export const mapStyles: Record<'light' | 'dark', StyleSpecification> = ${JSON.stringify(styles, null, 2)} as never;
`;

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(out, 'utf8');
  } catch {}
  if (current !== output) {
    console.error('map style drift: style.generated.ts is out of date. Run `npm run map`.');
    process.exit(1);
  }
} else {
  writeFileSync(out, output);
  console.log('build-map-style: wrote style.generated.ts');
}
