// Makes the small variants of the bundled content photos and writes the map Metro needs (every require written out).
//   NODE_PATH=$(dirname $(ls -d ~/.npm/_npx/*/node_modules/sharp | head -1)) npx -y -p sharp@0.34.5 node scripts/image-variants.mjs
// assets/images/content/<key>.jpg is the full size (800 px for shops, 400 for products, 640 for later shops). The
// variants go to content/w160/<key>.jpg and content/w400/<key>.jpg (JPEG q72, progressive), only when narrower than the
// original. imageSource() (src/content/images.ts) picks the smallest one that is still 2x (3x on iOS) the display
// width, so a 40 pt thumbnail decodes 160 px instead of 800.
import { createRequire } from 'node:module';
import { mkdirSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
// sharp is not a dependency of the app; npx puts it in its cache, and NODE_PATH points there (see the command above).
const sharp = require('sharp');

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const content = join(root, 'assets/images/content');
const SIZES = [160, 400];
const files = readdirSync(content).filter((f) => f.endsWith('.jpg')).sort();
for (const w of SIZES) mkdirSync(join(content, `w${w}`), { recursive: true });

// --recompress rewrites the full-size photos once at q80 (progressive, mozjpeg): 30% smaller, PSNR 29.6 dB at worst.
// Run it only on fresh downloads; a second pass would compress twice.
if (process.argv.includes('--recompress')) {
  for (const f of files) {
    const out = await sharp(join(content, f)).jpeg({ quality: 80, progressive: true, mozjpeg: true }).toBuffer();
    writeFileSync(join(content, f), out);
  }
}

const rows = [];
let bytes = 0;
for (const f of files) {
  const key = f.replace(/\.jpg$/, '');
  const full = sharp(join(content, f));
  const { width } = await full.metadata();
  const row = { key, width, sizes: [] };
  for (const w of SIZES) {
    if (w >= width) continue;
    // The photo picker's extra photos (`-photo-N`) are 400 px only: the web build's file count is tight.
    if (key.includes('-photo-') && w < 400) continue;
    // A photo of 640 px or less has no 400 px copy either: on the web (which skips 160) it would only add a file, and
    // the full photo is already small. The artifact that hosts the web build holds about 500 files.
    if (w === 400 && width <= 640) continue;
    const out = await sharp(join(content, f)).resize({ width: w }).jpeg({ quality: 72, progressive: true, mozjpeg: true }).toBuffer();
    writeFileSync(join(content, `w${w}`, f), out);
    bytes += out.length;
    row.sizes.push(w);
  }
  rows.push(row);
}

const req = (p) => `require('../../assets/images/content/${p}')`;
const lines = rows.map((r) => {
  const parts = [...r.sizes.map((w) => `${w}: ${req(`w${w}/${r.key}.jpg`)}`), `${r.width}: ${req(`${r.key}.jpg`)}`];
  return `  '${r.key}': { ${parts.join(', ')} },`;
});
writeFileSync(
  join(root, 'src/content/images.generated.ts'),
  `// Generated by scripts/image-variants.mjs. Do not edit. Each bundled photo by pixel width.\n\nexport const bundledImages: Record<string, Record<number, number>> = {\n${lines.join('\n')}\n};\n`,
);
console.log(`${rows.length} photos, variants ${(bytes / 1024).toFixed(0)} KB`);
